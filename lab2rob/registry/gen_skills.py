"""Generate lab2rob/registry/skills.yaml from biolab *Api classes + overlays.

Implemented skills are every public method of the ``*Api`` classes in
biolab/api.py, protein.py, culture.py and drug.py — the functions a policy may
call. Parsed with ``ast`` so generation never imports the simulator
(reference policies are string constants, not functions, and module-level
helpers like ``evaluate_*`` are correctly skipped: only ``*Api`` methods
count). Macros (macros.yaml) and declared skills (declared.yaml) are merged
in, and every macro is validated to bottom out in implemented primitives.

Usage: ``python lab2rob/registry/gen_skills.py [--check]``
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
BIOLAB = REPO_ROOT / "Code-as-a-Policy-Evolving-Skill" / "biolab"
API_FILES = [BIOLAB / name for name in ("api.py", "protein.py", "culture.py", "drug.py")]
HERE = Path(__file__).resolve().parent
SKILLS_PATH = HERE / "skills.yaml"
MACROS_PATH = HERE / "macros.yaml"
DECLARED_PATH = HERE / "declared.yaml"

HEADER = (
    "# THIS FILE IS GENERATED by lab2rob/registry/gen_skills.py — do not edit by hand.\n"
    "# Implemented skills come from the biolab *Api classes; macros from macros.yaml;\n"
    "# declared skills from declared.yaml. Regenerate: python lab2rob/registry/gen_skills.py\n"
)

#: Methods that exist on the Api classes but are not policy-callable skills.
SKIP_METHODS = {"functions"}


def _signature(fn: ast.FunctionDef) -> str:
    args = ast.unparse(fn.args)
    if args == "self":
        args = ""
    elif args.startswith("self, "):
        args = args[len("self, "):]
    returns = ast.unparse(fn.returns) if fn.returns else "None"
    return f"({args}) -> {returns}"


def _variant(fn: ast.FunctionDef, module: str) -> dict:
    doc = ast.get_docstring(fn, clean=True)
    variant = {"module": module, "signature": _signature(fn),
               "doc": doc if doc is not None else ""}
    if doc is None:
        variant["note"] = "docstring assigned dynamically at runtime; read biolab sources"
    return variant


def extract(api_files=API_FILES) -> dict:
    """{skill name: {"kind": ..., "variants": {class: {...}}}} from *Api methods."""
    skills: dict[str, dict] = {}
    for path in api_files:
        module = f"biolab.{path.stem}"
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in tree.body:
            if not (isinstance(node, ast.ClassDef) and "Api" in node.name):
                continue
            for item in node.body:
                if not isinstance(item, ast.FunctionDef):
                    continue
                if item.name.startswith("_") or item.name in SKIP_METHODS:
                    continue
                entry = skills.setdefault(
                    item.name,
                    {"kind": "query" if item.name.startswith("get_") else "action",
                     "variants": {}})
                entry["variants"][node.name] = _variant(item, module)
    return skills


def _load_yaml(path: Path) -> dict:
    import yaml

    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def validate_macros(macros: list, implemented: set, by_name: dict) -> None:
    """Every macro step must resolve, and transitive closure must be implemented."""
    for macro in macros:
        name = macro["name"]
        if name in implemented or name in by_name and by_name[name] != "macro":
            raise ValueError(f"Macro {name!r} collides with a non-macro skill")
        seen, stack = set(), list(macro.get("steps", []))
        while stack:
            step = stack.pop()
            if step in seen:
                continue
            seen.add(step)
            if step in implemented:
                continue
            target = next((m for m in macros if m["name"] == step), None)
            if target is None:
                raise ValueError(f"Macro {name!r} uses unknown/non-implemented {step!r}")
            stack.extend(target.get("steps", []))
        if name in seen:
            raise ValueError(f"Macro {name!r} is recursive")


def generate() -> str:
    import yaml

    implemented = extract()
    macros = _load_yaml(MACROS_PATH).get("macros", [])
    declared = _load_yaml(DECLARED_PATH).get("declared_skills", [])

    by_name = {n: "implemented" for n in implemented}
    for macro in macros:
        if macro["name"] in by_name:
            raise ValueError(f"Macro {macro['name']!r} collides with {by_name[macro['name']]} skill")
        by_name[macro["name"]] = "macro"
    for skill in declared:
        if skill["name"] in by_name:
            raise ValueError(f"Declared skill {skill['name']!r} collides with {by_name[skill['name']]} skill")
        by_name[skill["name"]] = "declared"
    validate_macros(macros, set(implemented), by_name)

    entries = []
    for name in sorted(implemented):
        variants = implemented[name]["variants"]
        entries.append({"name": name, "status": "implemented",
                        "kind": implemented[name]["kind"],
                        "variants": {owner: variants[owner] for owner in sorted(variants)}})
    for macro in sorted(macros, key=lambda m: m["name"]):
        entries.append({"name": macro["name"], "status": "macro", "kind": macro["kind"],
                        "description": macro["description"],
                        "params": list(macro.get("params", [])),
                        "steps": list(macro.get("steps", []))})
    for skill in sorted(declared, key=lambda s: s["name"]):
        entries.append({"name": skill["name"], "status": "declared", "kind": skill["kind"],
                        "description": skill["description"]})
    entries.sort(key=lambda e: e["name"])
    body = yaml.safe_dump({"skills": entries}, sort_keys=False, width=1000,
                          allow_unicode=True)
    return HEADER + body


def main(argv: list[str]) -> int:
    check = "--check" in argv
    text = generate()
    if check:
        current = SKILLS_PATH.read_text(encoding="utf-8") if SKILLS_PATH.exists() else ""
        if current != text:
            print(f"{SKILLS_PATH} is stale; regenerate with "
                  "python lab2rob/registry/gen_skills.py")
            return 1
        print(f"{SKILLS_PATH} is current.")
        return 0
    SKILLS_PATH.write_text(text, encoding="utf-8")
    print(f"Wrote {SKILLS_PATH}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
